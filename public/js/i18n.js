/* Выбор языка: ?lang=kk в ссылке → сохранённый выбор → язык браузера → русский */
const LANG_KEY = 'gm_lang';
function applyLang(l) {
  LANG = l === 'kk' ? 'kk' : 'ru';
  try { localStorage.setItem(LANG_KEY, LANG); } catch { /* приватный режим */ }
  document.documentElement.lang = LANG;
  document.title = T('title');
}
(() => {
  let l = new URLSearchParams(location.search).get('lang');
  if (!l) { try { l = localStorage.getItem(LANG_KEY); } catch { l = null; } }
  if (!l) l = /^kk/i.test(navigator.language || '') ? 'kk' : 'ru';
  applyLang(l);
})();

